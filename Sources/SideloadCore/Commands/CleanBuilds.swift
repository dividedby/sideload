import Darwin
import Foundation

/// The build-output half of `clean`: what under `$SIDELOAD_HOME/builds/` is no longer needed (issue #49, design section 18).
/// Output is counts and bytes only; the plan holds paths for the deletion step alone.
///
/// - **Signed builds** (`builds/signed/<app>/<alias>`): deleted only when the ledger proves the build is the one installed on
///   that device and it was signed more than `CleanCommand.retentionDays` days ago. Anything that cannot be proven is kept.
///   Such a build's free profile has expired by then, so `install` already answers `PROFILE_EXPIRED` for it and `refresh`
///   provisions and signs again from the kept IPA; `clean` writes nothing to the ledger.
/// - **Orphans:** an app folder of an app that is neither in the registry nor in the ledger, an alias folder of a device that
///   is neither saved nor in the ledger, and an app folder left empty. No age gate.
/// - **Caches:** `builds/carrier-dd` and `builds/canary`, whole, at any age. Under `.op.lock` no `provision` or `canary` is
///   running, and both rebuild what they need. `builds/carrier` is regenerated by every `provision` and is left alone.
///
/// A device with a lent slot or an operation in its window (`DeviceRemove.refusal`) is skipped whole. Nothing is followed: a
/// link at any level, or inside a folder that would be deleted, keeps that folder. Never `profiles/free/`, never a device.
enum CleanBuilds {
    enum Kind: Equatable {
        case signed, orphan, cache
        /// An app folder with nothing left in it once the planned deletions are done (`rmdir`, never recursive).
        case emptyApp
    }

    struct Item: Equatable {
        var path: String
        var kind: Kind
        var bytes: Int64
    }

    struct Counts: Equatable {
        var signedDeleted = 0
        var signedKept = 0
        var orphansDeleted = 0
        var cachesDeleted = 0
        var bytesFreed: Int64 = 0
        var failed = 0
        var devicesSkippedBusy = 0
        var linksSkipped = 0

        var deleted: Int { signedDeleted + orphansDeleted + cachesDeleted }

        var json: [String: JSONValue] {
            [
                "signedDeleted": .number(Double(signedDeleted)),
                "signedKept": .number(Double(signedKept)),
                "orphansDeleted": .number(Double(orphansDeleted)),
                "cachesDeleted": .number(Double(cachesDeleted)),
                "bytesFreed": .number(Double(bytesFreed)),
                "failed": .number(Double(failed)),
                "devicesSkippedBusy": .number(Double(devicesSkippedBusy)),
                "linksSkipped": .number(Double(linksSkipped)),
            ]
        }

        mutating func add(_ item: Item, _ sign: Int) {
            switch item.kind {
            case .signed: signedDeleted += sign
            case .orphan, .emptyApp: orphansDeleted += sign
            case .cache: cachesDeleted += sign
            }
            bytesFreed += Int64(sign) * item.bytes
        }
    }

    struct Plan: Equatable {
        /// In deletion order: an app folder's `emptyApp` comes after the folders inside it.
        var items: [Item] = []
        var counts = Counts()
    }

    /// What the ledger and config say exists.
    private struct Known {
        var apps: Set<String>
        var aliases: Set<String>
    }

    // MARK: plan

    /// `ledger` must be the migrated one (`SlotRule.migrated`), the way `DeviceRemove` reads busy and `present`. Read-only.
    static func plan(_ services: Services, config: Config, ledger: Ledger, now: Date) -> Plan {
        var plan = Plan()
        let home = services.home
        let known = Known(
            apps: Set(config.appRegistry.names)
                .union(ledger.freeSigned.map(\.app)).union(ledger.installs.map(\.app))
                .union(ledger.slots.map(\.app)).union(ledger.freeProfiles.map(\.app))
                .union(ledger.lent.map(\.app)),
            aliases: Set(config.devices.keys)
                .union(ledger.freeSigned.map(\.device)).union(ledger.installs.map(\.device))
                .union(ledger.slots.map(\.device)).union(ledger.freeProfiles.map(\.device))
                .union(ledger.lent.map(\.device)))
        let cutoff = now.addingTimeInterval(-CleanCommand.retention)
        var busyAliases = Set<String>()

        for app in folders(
            in: home.signedBuilds, root: home.builds, links: &plan.counts.linksSkipped)
        {
            let appDir = home.signedBuilds + "/" + app
            let aliases = folders(in: appDir, root: home.builds, links: &plan.counts.linksSkipped)
            if !known.apps.contains(app) {
                let tree = scan(appDir)
                let busy = aliases.contains { isBusy($0, ledger, now) }
                if tree.links == 0 && !busy {
                    plan.items.append(Item(path: appDir, kind: .orphan, bytes: tree.bytes))
                    plan.counts.add(plan.items[plan.items.count - 1], 1)
                    continue
                }
            }
            var doomed = Set<String>()
            for alias in aliases {
                let folder = appDir + "/" + alias
                if isBusy(alias, ledger, now) {
                    busyAliases.insert(alias)
                    plan.counts.signedKept += 1
                    continue
                }
                let tree = scan(folder)
                if tree.links > 0 {
                    plan.counts.linksSkipped += 1
                    continue
                }
                let kind: Kind?
                if !known.aliases.contains(alias) {
                    kind = .orphan
                } else if installedAndOld(
                    app: app, alias: alias, folder: folder, ledger: ledger, home: home,
                    cutoff: cutoff)
                {
                    kind = .signed
                } else {
                    kind = nil
                }
                guard let kind else {
                    plan.counts.signedKept += 1
                    continue
                }
                let item = Item(path: folder, kind: kind, bytes: tree.bytes)
                plan.items.append(item)
                plan.counts.add(item, 1)
                doomed.insert(alias)
            }
            // Counted when the folder is empty to begin with, too.
            if Set(DeviceRemove.names(in: appDir)).subtracting(doomed).isEmpty {
                let item = Item(path: appDir, kind: .emptyApp, bytes: 0)
                plan.items.append(item)
                plan.counts.add(item, 1)
            }
        }
        plan.counts.devicesSkippedBusy = busyAliases.count

        for cache in [home.carrierDerivedData, home.canaryDerivedData] {
            if DeviceRemove.isLink(cache) {
                plan.counts.linksSkipped += 1
            } else if AppDataBackup.isPlain(cache, root: home.builds, regularFile: false) {
                let item = Item(path: cache, kind: .cache, bytes: scan(cache).bytes)
                plan.items.append(item)
                plan.counts.add(item, 1)
            }
        }
        return plan
    }

    private static func isBusy(_ alias: String, _ ledger: Ledger, _ now: Date) -> Bool {
        DeviceRemove.refusal(ledger.slots, alias: alias, now: now) != nil
    }

    /// The ledger shows this folder's build is what is installed on the device: a `freeSigned` record whose path is inside the
    /// folder, an `installs[]` record that is present with the same profile, version, hash prefix and signing time, and a
    /// signing time more than the retention ago.
    private static func installedAndOld(
        app: String, alias: String, folder: String, ledger: Ledger, home: Paths, cutoff: Date
    ) -> Bool {
        let id = "\(alias)/\(app)"
        guard let signed = ledger.freeSigned.first(where: { $0.id == id }),
            let install = ledger.installs.first(where: { $0.id == id }), install.present,
            install.profileUuid == signed.profileUuid, install.version == signed.version,
            install.sha256Prefix == signed.sha256Prefix, install.signedAt == signed.signedAt,
            signed.signedAt < cutoff
        else { return false }
        let path = resolvePath(home.home + "/" + signed.path)
        let root = resolvePath(folder)
        return path == root || path.hasPrefix(root + "/")
    }

    // MARK: apply

    /// Deletes the plan's folders and returns the counts as they ended. A folder whose chain is no longer plain, or that cannot
    /// be removed, is `failed` and not deleted.
    static func apply(_ plan: Plan, services: Services) -> Counts {
        var counts = plan.counts
        let root = services.home.builds
        for item in plan.items {
            var removed = false
            if item.kind == .emptyApp {
                if AppDataBackup.isPlain(item.path, root: root, regularFile: false) {
                    removed = rmdir(item.path) == 0
                    // An app folder a failed deletion left full is that failure's, already counted.
                    if !removed && errno == ENOTEMPTY {
                        counts.add(item, -1)
                        continue
                    }
                }
            } else {
                removed = CleanCommand.removePlainFolder(item.path, root: root)
            }
            if !removed {
                counts.add(item, -1)
                counts.failed += 1
            }
        }
        return counts
    }

    // MARK: reading

    /// The names of the real, non-hidden folders directly inside `directory`, sorted. Counts a link met (the folder itself or an
    /// entry) in `links`. Nothing inside is opened.
    private static func folders(in directory: String, root: String, links: inout Int) -> [String] {
        if DeviceRemove.isLink(directory) {
            links += 1
            return []
        }
        guard AppDataBackup.isPlain(directory, root: root, regularFile: false) else { return [] }
        var found: [String] = []
        for name in DeviceRemove.names(in: directory) where !name.hasPrefix(".") {
            let path = directory + "/" + name
            if DeviceRemove.isRealDirectory(path) {
                found.append(name)
            } else if DeviceRemove.isLink(path) {
                links += 1
            }
        }
        return found
    }

    /// Bytes of the regular files under `path` and the links met, by `lstat`, nothing followed.
    private static func scan(_ path: String) -> (bytes: Int64, links: Int) {
        var st = stat()
        guard lstat(path, &st) == 0 else { return (0, 0) }
        switch st.st_mode & S_IFMT {
        case S_IFREG: return (Int64(st.st_size), 0)
        case S_IFLNK: return (0, 1)
        case S_IFDIR:
            var total: (bytes: Int64, links: Int) = (0, 0)
            for name in DeviceRemove.names(in: path) {
                let part = scan(path + "/" + name)
                total.bytes += part.bytes
                total.links += part.links
            }
            return total
        default: return (0, 0)
        }
    }
}
